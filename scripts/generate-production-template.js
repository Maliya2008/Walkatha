import fs from 'fs';
import path from 'path';

const distHtmlPath = path.resolve(process.cwd(), 'dist', 'index.html');

if (!fs.existsSync(distHtmlPath)) {
  console.error('[Template Generator Error]: dist/index.html does not exist. Run vite build first.');
  process.exit(1);
}

const htmlContent = fs.readFileSync(distHtmlPath, 'utf8');

if (!htmlContent.includes('/assets/') || !htmlContent.includes('id="root"')) {
  console.error('[Template Generator Error]: dist/index.html is missing asset links or #root element.');
  process.exit(1);
}

// 1. Ensure src/generated directory exists
const generatedDir = path.resolve(process.cwd(), 'src', 'generated');
if (!fs.existsSync(generatedDir)) {
  fs.mkdirSync(generatedDir, { recursive: true });
}

// 2. Write src/generated/productionTemplate.ts
const codeContent = `// Auto-generated by scripts/generate-production-template.js - DO NOT EDIT MANUALLY
export const PRODUCTION_HTML_TEMPLATE: string = ${JSON.stringify(htmlContent)};
`;

fs.writeFileSync(path.join(generatedDir, 'productionTemplate.ts'), codeContent, 'utf8');
console.log('✔ Successfully generated src/generated/productionTemplate.ts');

// 3. Ensure build directory exists and copy dist/index.html to build/index.html
const buildDir = path.resolve(process.cwd(), 'build');
if (!fs.existsSync(buildDir)) {
  fs.mkdirSync(buildDir, { recursive: true });
}
fs.writeFileSync(path.join(buildDir, 'index.html'), htmlContent, 'utf8');
console.log('✔ Successfully copied dist/index.html to build/index.html');
